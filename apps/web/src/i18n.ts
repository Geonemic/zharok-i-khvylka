export type Lang = 'uk' | 'en';
const DICTS: Record<Lang, Record<TKey, string>> = { uk, en };
export const LANGS: { id: Lang; label: string }[] = [{ id: 'uk', label: 'УКР' }, { id: 'en', label: 'ENG' }];

let lang: Lang = 'uk';
try { const saved = localStorage.getItem('zh-lang'); if (saved === 'uk' || saved === 'en') lang = saved; } catch { /* без сховища — мова за замовчуванням */ }
const listeners = new Set<() => void>();

export function setLang(l: Lang) {
  lang = l;
  try { localStorage.setItem('zh-lang', l); } catch { /* лише на цю сесію */ }
  document.documentElement.lang = l;
  listeners.forEach((f) => f());
}

export function translate(l: Lang, key: string, vars?: Record<string, string | number>): string {
  let s = DICTS[l][key as TKey] ?? DICTS.uk[key as TKey] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
  return s;
}

export function useLang() {
  const l = useSyncExternalStore((cb) => { listeners.add(cb); return () => listeners.delete(cb); }, () => lang);
  const t = useCallback((key: TKey | string, vars?: Record<string, string | number>) => translate(l, key, vars), [l]);
  return { lang: l, t, setLang };
}
